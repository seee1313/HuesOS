//! Static x86-interrupt ABI stubs for the dynamically allocated I/O-APIC
//! vector range. The CPU does not push the vector number on the interrupt
//! stack, so each IDT slot needs a tiny vector-specific entry point.

use x86_64::structures::idt::{InterruptDescriptorTable, InterruptStackFrame};

macro_rules! define_ioapic_handlers {
    ($(($name:ident, $vector:expr)),* $(,)?) => {
        $(
            extern "x86-interrupt" fn $name(_frame: InterruptStackFrame) {
                dispatch_external_irq($vector);
            }
        )*

        pub(super) fn install(idt: &mut InterruptDescriptorTable) {
            $(idt[$vector].set_handler_fn($name);)*
        }
    };
}

fn dispatch_external_irq(vector: u8) {
    super::cpu::clear_user_access();
    // Level-triggered routes must be masked before EOI so the asserted line
    // cannot immediately re-enter while userspace is servicing the device.
    let _ = super::ioapic::begin_interrupt(vector);
    super::lapic::eoi();
    super::ioapic::dispatch_vector(vector);
}

